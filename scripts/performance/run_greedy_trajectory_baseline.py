def to_jsonable(obj: Any) -> Any:
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return float(obj)
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    if isinstance(obj, dict):
        return {str(k): to_jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [to_jsonable(v) for v in obj]
    return obj


def vec_to_list(x: np.ndarray) -> list[int]:
    return [int(v) for v in np.asarray(x).reshape(-1)]


def normalize_lattice_vector(x: np.ndarray) -> np.ndarray:
    return np.rint(np.asarray(x)).astype(int)


def parse_list_field(x: Any) -> list[int] | None:
    if x is None:
        return None
    if isinstance(x, list):
        return [int(v) for v in x]
    if isinstance(x, np.ndarray):
        return [int(v) for v in x.reshape(-1)]
    if isinstance(x, str):
        s = x.strip()
        if not s:
            return None
        try:
            parsed = ast.literal_eval(s)
        except Exception:
            return None
        if isinstance(parsed, (list, tuple)):
            return [int(v) for v in parsed]
    return None


def parse_bool_field(x: Any) -> bool:
    if isinstance(x, (bool, np.bool_)):
        return bool(x)
    if isinstance(x, (int, np.integer)):
        return bool(int(x))
    if isinstance(x, float):
        return bool(int(x))
    if isinstance(x, str):
        s = x.strip().lower()
        if s in {"true", "1", "yes", "y"}:
            return True
        if s in {"false", "0", "no", "n", ""}:
            return False
    return bool(x)


def append_csv_row(path: Path, row: dict[str, Any], fieldnames: list[str]) -> None:
    file_exists = path.exists() and path.stat().st_size > 0
    with path.open("a", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        if not file_exists:
            writer.writeheader()
        writer.writerow({k: row.get(k, "") for k in fieldnames})
        f.flush()
        os.fsync(f.fileno())


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def append_jsonl(path: Path, item: dict[str, Any]) -> None:
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(to_jsonable(item), ensure_ascii=False) + "\n")
        f.flush()
        os.fsync(f.fileno())


def sanitize_filename_part(x: Any) -> str:
    s = str(x).strip()
    if not s:
        return "untagged"
    return "".join(ch if (ch.isalnum() or ch in {"-", "_"}) else "_" for ch in s)


def resolve_input_path(path_str: str | None) -> Path | None:
    if not path_str:
        return None
    p = Path(path_str).expanduser()
    if p.is_absolute():
        return p.resolve()

    project_candidate = (PROJECT_ROOT / p).resolve()
    cwd_candidate = p.resolve()
    if project_candidate.exists():
        return project_candidate
    if cwd_candidate.exists():
        return cwd_candidate
    return project_candidate


def resolve_max_workers(cfg: dict[str, Any]) -> int:
    requested = cfg.get("max_workers", None)
    cpu_count = os.cpu_count() or 1
    if requested is None:
        return max(1, cpu_count - 1)
    try:
        requested_int = int(requested)
    except (TypeError, ValueError):
        return max(1, cpu_count - 1)
    if requested_int <= 0:
        return max(1, cpu_count - 1)
    return max(1, min(requested_int, cpu_count))


