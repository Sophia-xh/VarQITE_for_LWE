# 5) One seed from source raw
# =========================================================
def compute_one_classical_row(
    source_record: dict[str, Any],
    source_cfg: dict[str, Any],
    local_cfg: dict[str, Any],
) -> tuple[ClassicalOnlyRow | None, dict[str, Any] | None]:
    t0_total = time.perf_counter()

    n = int(source_record["n"])
    m = int(source_record["m"])
    q = int(source_record["q"])
    seed = int(source_record["seed"])

    inst = safe_generate_instance(n=n, m=m, q=q, seed=seed, source_cfg=source_cfg)
    if inst is None:
        return None, None

    # Cheap regeneration of lattice objects
    B, _, _ = full_rank_basis_from_hnf(inst.A, q)
    D = reduce_basis(B, method=source_cfg["reduction_method"], delta=source_cfg["delta_lll"])

    w_babai, _ = babai_nearest_plane(D, inst.c_centered)
    w_babai = normalize_lattice_vector(w_babai)
    residual = np.asarray(inst.c_centered, dtype=int) - w_babai

    s_hat_babai = recover_secret_from_lattice_point(inst.A, w_babai, q)
    regenerated_babai_success = bool(np.array_equal(s_hat_babai % q, inst.s_mod_q % q))

    # Greedy is cheap and provides trajectory candidates.
    t0_greedy = time.perf_counter()
    greedy_res = greedy_local_from_babai(
        D=D,
        residual=residual,
        values=tuple(source_cfg["local_values"]),
        max_steps=source_cfg["greedy_max_steps"],
        tol=source_cfg["greedy_tol"],
    )
    elapsed_greedy_sec = float(time.perf_counter() - t0_greedy)

    delta_greedy = np.asarray(greedy_res.delta_greedy, dtype=int)
    w_greedy = normalize_lattice_vector(w_babai + D @ delta_greedy)
    s_hat_greedy = recover_secret_from_lattice_point(inst.A, w_greedy, q)
    regenerated_greedy_success = bool(np.array_equal(s_hat_greedy % q, inst.s_mod_q % q))

    rerank_config = make_candidate_rerank_config(source_cfg)
    generation_config = make_classical_generation_config(local_cfg, source_cfg)

    delta_exact = parse_list_field(source_record.get("delta_exact"))
    exact_best_energy = source_record.get("exact_best_energy", None)
    if exact_best_energy is not None and not (isinstance(exact_best_energy, float) and math.isnan(exact_best_energy)):
        exact_best_energy = float(exact_best_energy)
    else:
        exact_best_energy = None

    t0_classical_candidate = time.perf_counter()
    classical_res = rerank_classical_local_candidates(
        inst=inst,
        D=D,
        w_babai=w_babai,
        residual=residual,
        q=q,
        greedy_result=greedy_res,
        rerank_config=rerank_config,
        generation_config=generation_config,
        delta_exact=np.asarray(delta_exact, dtype=int) if delta_exact is not None else None,
        exact_best_energy=exact_best_energy,
    )
    elapsed_classical_candidate_sec = float(time.perf_counter() - t0_classical_candidate)

    best = classical_res.best_candidate

    # Saved labels from the source main-experiment run
    source_babai_success = parse_bool_field(source_record["babai_secret_success"])
    source_exact_success = parse_bool_field(source_record["exact_secret_success"])
    source_greedy_success = parse_bool_field(source_record["classical_secret_success"])
    source_qite_primary_success = parse_bool_field(source_record["qite_primary_secret_success"])
    source_qite_candidate_success = parse_bool_field(source_record["qite_candidate_best_secret_success"])
    source_qite_candidate_any_success = parse_bool_field(source_record["qite_candidate_any_secret_success"])

    source_babai_fail_qite_best_fix = parse_bool_field(
        source_record["babai_fail_but_qite_candidate_best_fix"]
    )
    source_babai_fail_qite_any_fix = parse_bool_field(
        source_record["babai_fail_but_qite_candidate_any_fix"]
    )

    classical_candidate_success = bool(best["secret_success"])
    babai_fail_but_classical_fix = bool((not source_babai_success) and classical_candidate_success)

    qite_success_but_classical_fail = bool(
        source_qite_candidate_success and not classical_candidate_success
    )
    classical_success_but_qite_fail = bool(
        classical_candidate_success and not source_qite_candidate_success
    )
    both_success = bool(source_qite_candidate_success and classical_candidate_success)
    both_fail = bool((not source_qite_candidate_success) and (not classical_candidate_success))

    # Validation against the source raw_per_seed.csv. These should match.
    src_w_babai = parse_list_field(source_record.get("w_babai"))
    src_residual = parse_list_field(source_record.get("residual"))
    w_babai_match = bool(src_w_babai == vec_to_list(w_babai)) if src_w_babai is not None else False
    residual_match = bool(src_residual == vec_to_list(residual)) if src_residual is not None else False
    babai_success_match = bool(regenerated_babai_success == source_babai_success)
    greedy_success_match = bool(regenerated_greedy_success == source_greedy_success)

    validation_issue = None
    if not (w_babai_match and residual_match and babai_success_match and greedy_success_match):
        validation_issue = {
            "n": n,
            "m": m,
            "q": q,
            "seed": seed,
            "validation_w_babai_match": w_babai_match,
            "validation_residual_match": residual_match,
            "validation_babai_success_match": babai_success_match,
            "validation_greedy_success_match": greedy_success_match,
            "source_w_babai": src_w_babai,
            "regenerated_w_babai": vec_to_list(w_babai),
            "source_residual": src_residual,
            "regenerated_residual": vec_to_list(residual),
        }

    w_true = np.asarray(inst.w_true, dtype=int)
    dist2_true_babai = int(np.sum((w_babai - w_true) ** 2))
    dist2_true_classical_best = int(best["dist2_true"])
    classical_geometry_improved = bool(dist2_true_classical_best < dist2_true_babai)

    elapsed_total_sec = float(time.perf_counter() - t0_total)

    row = ClassicalOnlyRow(
        n=n,
        m=m,
        q=q,
        seed=seed,

        source_babai_secret_success=bool(source_babai_success),
        source_exact_secret_success=bool(source_exact_success),
        source_classical_greedy_secret_success=bool(source_greedy_success),
        source_varqite_primary_secret_success=bool(source_qite_primary_success),
        source_varqite_candidate_lwe_prior_success=bool(source_qite_candidate_success),
        source_varqite_candidate_any_success=bool(source_qite_candidate_any_success),

        source_babai_fail_but_qite_candidate_best_fix=bool(source_babai_fail_qite_best_fix),
        source_babai_fail_but_qite_candidate_any_fix=bool(source_babai_fail_qite_any_fix),

        regenerated_babai_secret_success=bool(regenerated_babai_success),
        regenerated_greedy_secret_success=bool(regenerated_greedy_success),
        validation_babai_success_match=bool(babai_success_match),
        validation_greedy_success_match=bool(greedy_success_match),
        validation_w_babai_match=bool(w_babai_match),
        validation_residual_match=bool(residual_match),

        delta_classical_candidate_best=best["delta"],
        classical_candidate_best_energy=float(best["energy"]),
        classical_candidate_best_lwe_prior_score=float(best["lwe_prior_score"]),
        classical_candidate_best_secret_ternary_violation=int(best["secret_ternary_violation"]),
        classical_candidate_best_noise_ternary_violation=int(best["noise_ternary_violation"]),
        classical_candidate_best_secret_weight=int(best["secret_weight"]),
        classical_candidate_best_noise_weight=int(best["noise_weight"]),
        w_classical_candidate_best=best["w_candidate"],
        s_hat_classical_candidate_best=best["s_hat"],
        classical_candidate_best_secret_success=bool(classical_candidate_success),

        classical_candidate_generated_raw=int(classical_res.candidate_num_generated_raw),
        classical_candidate_topk_used=int(classical_res.candidate_topk_used),
        classical_candidate_any_secret_success=bool(classical_res.any_secret_success),
        classical_candidate_any_geometry_improved=bool(classical_res.any_geometry_improved),
        classical_candidate_any_matches_exact_state=bool(classical_res.any_matches_exact_state),
        classical_candidate_any_matches_exact_energy=bool(classical_res.any_matches_exact_energy),
        classical_min_dist2_true_among_candidates=classical_res.min_dist2_true_among_candidates,
        classical_candidate_preview_states=classical_res.candidate_preview_states,

        babai_fail_but_classical_candidate_fix=bool(babai_fail_but_classical_fix),

        qite_candidate_success_but_classical_candidate_fail=bool(qite_success_but_classical_fail),
        classical_candidate_success_but_qite_candidate_fail=bool(classical_success_but_qite_fail),
        qite_candidate_and_classical_candidate_both_success=bool(both_success),
        qite_candidate_and_classical_candidate_both_fail=bool(both_fail),

        dist2_true_babai=int(dist2_true_babai),
        dist2_true_classical_candidate_best=int(dist2_true_classical_best),
        classical_candidate_best_geometry_improved=bool(classical_geometry_improved),

        elapsed_total_sec=float(elapsed_total_sec),
        elapsed_greedy_sec=float(elapsed_greedy_sec),
        elapsed_classical_candidate_sec=float(elapsed_classical_candidate_sec),
    )
    return row, validation_issue


def worker(args: tuple[dict[str, Any], dict[str, Any], dict[str, Any]]):
    source_record, source_cfg, local_cfg = args
    try:
        row, validation_issue = compute_one_classical_row(source_record, source_cfg, local_cfg)
        seed = int(source_record["seed"])
        return seed, row, validation_issue, None
    except Exception:
        seed = int(source_record.get("seed", -1))
        return seed, None, None, traceback.format_exc()


