# 6) Summary and merging
# =========================================================
def summarize_rows(rows: list[ClassicalOnlyRow]) -> list[dict[str, Any]]:
    grouped: dict[tuple[int, int, int], list[ClassicalOnlyRow]] = {}
    for row in rows:
        grouped.setdefault((row.n, row.m, row.q), []).append(row)

    summary_rows: list[dict[str, Any]] = []
    for (n, m, q), group in sorted(grouped.items()):
        if not group:
            continue

        failed_group = [r for r in group if not r.source_babai_secret_success]

        def mean_bool(attr: str) -> float:
            return float(np.mean([bool(getattr(r, attr)) for r in group]))

        def mean_num(attr: str) -> float:
            return float(np.mean([float(getattr(r, attr)) for r in group]))

        def conditional_mean(attr: str, subset: list[ClassicalOnlyRow]) -> float | str:
            if not subset:
                return ""
            return float(np.mean([bool(getattr(r, attr)) for r in subset]))

        net_win = (
            mean_bool("qite_candidate_success_but_classical_candidate_fail")
            - mean_bool("classical_candidate_success_but_qite_candidate_fail")
        )

        summary_rows.append(
            {
                "n": int(n),
                "m": int(m),
                "q": int(q),
                "num_seeds": int(len(group)),
                "num_babai_failures": int(len(failed_group)),

                # Metrics reused from the source main-experiment run
                "babai_secret_success_rate": mean_bool("source_babai_secret_success"),
                "exact_local_energy_oracle_success_rate": mean_bool("source_exact_secret_success"),
                "classical_greedy_success_rate": mean_bool("source_classical_greedy_secret_success"),
                "varqite_primary_success_rate": mean_bool("source_varqite_primary_secret_success"),
                "varqite_candidate_lwe_prior_success_rate": mean_bool(
                    "source_varqite_candidate_lwe_prior_success"
                ),
                "varqite_candidate_any_success_rate": mean_bool(
                    "source_varqite_candidate_any_success"
                ),

                # New fair classical metrics
                "greedy_trajectory_candidate_lwe_prior_success_rate": mean_bool(
                    "classical_candidate_best_secret_success"
                ),
                "greedy_trajectory_candidate_any_success_rate": mean_bool(
                    "classical_candidate_any_secret_success"
                ),

                # Repair among all instances
                "babai_fail_but_greedy_trajectory_candidate_fix_rate": mean_bool(
                    "babai_fail_but_classical_candidate_fix"
                ),
                "babai_fail_but_qite_candidate_fix_rate": mean_bool(
                    "source_babai_fail_but_qite_candidate_best_fix"
                ),

                # Conditional repair among Babai failures
                "greedy_trajectory_candidate_fix_rate_among_babai_failures": conditional_mean(
                    "classical_candidate_best_secret_success", failed_group
                ),
                "qite_candidate_fix_rate_among_babai_failures": conditional_mean(
                    "source_varqite_candidate_lwe_prior_success", failed_group
                ),

                # Direct fair pairwise comparison
                "qite_candidate_success_but_greedy_trajectory_candidate_fail_rate": mean_bool(
                    "qite_candidate_success_but_classical_candidate_fail"
                ),
                "greedy_trajectory_candidate_success_but_qite_fail_rate": mean_bool(
                    "classical_candidate_success_but_qite_candidate_fail"
                ),
                "qite_candidate_and_classical_candidate_both_success_rate": mean_bool(
                    "qite_candidate_and_classical_candidate_both_success"
                ),
                "qite_candidate_and_classical_candidate_both_fail_rate": mean_bool(
                    "qite_candidate_and_classical_candidate_both_fail"
                ),
                "qite_minus_greedy_trajectory_candidate_net_win_rate": float(net_win),

                # Candidate-pool diagnostics
                "avg_greedy_trajectory_candidate_generated_raw": mean_num(
                    "classical_candidate_generated_raw"
                ),
                "avg_greedy_trajectory_candidate_topk_used": mean_num(
                    "classical_candidate_topk_used"
                ),

                # Validation
                "validation_babai_success_match_rate": mean_bool(
                    "validation_babai_success_match"
                ),
                "validation_greedy_success_match_rate": mean_bool(
                    "validation_greedy_success_match"
                ),
                "validation_w_babai_match_rate": mean_bool("validation_w_babai_match"),
                "validation_residual_match_rate": mean_bool("validation_residual_match"),

                # Time
                "avg_classical_only_total_time_sec": mean_num("elapsed_total_sec"),
                "avg_greedy_time_sec": mean_num("elapsed_greedy_sec"),
                "avg_greedy_trajectory_candidate_rerank_time_sec": mean_num(
                    "elapsed_classical_candidate_sec"
                ),
            }
        )

    return summary_rows


def build_merged_raw(source_df: pd.DataFrame, classical_rows: list[ClassicalOnlyRow]) -> pd.DataFrame:
    classical_df = pd.DataFrame([asdict(r) for r in classical_rows])
    key_cols = ["n", "m", "q", "seed"]
    merged = source_df.merge(
        classical_df,
        on=key_cols,
        how="left",
        # These suffixes are part of the archived merged CSV's column names.
        suffixes=("_exp11", "_classical_fair"),
        validate="one_to_one",
    )
    return merged.sort_values(key_cols).reset_index(drop=True)


