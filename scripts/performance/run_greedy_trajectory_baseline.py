"""
run_greedy_trajectory_baseline.py
=================================

Greedy-trajectory baseline for the fair comparison in Figure 3(b). It REUSES the
VarQITE results of an existing main-experiment run instead of re-running VarQITE.

This script produced the archived data in
data/figure3_performance_comparison/greedy_baseline/.

Why this script exists
----------------------
Re-running VarQITE is unnecessary once a main-experiment run has already
produced:
    - raw_per_seed.csv
    - config.json

This script:
    1. reads an existing main-experiment run directory;
    2. regenerates the SAME LWE instances from the stored config and seeds;
    3. recomputes only the CHEAP classical part:
         - q-ary lattice basis and reduction
         - Babai
         - greedy local baseline
         - greedy-trajectory candidate pool + SAME LWE-prior reranking
    4. merges the new classical candidate results with the already-saved
       VarQITE candidate results from the main experiment's raw_per_seed.csv.

No VarQITE call is made in this script, so it is fast.

Inputs
------
--source_run_dir:
    The main-experiment run directory containing:
        raw_per_seed.csv
        config.json
    Default: data/figure3_performance_comparison/main_experiment

Outputs
-------
<ARTIFACT_ROOT>/
  output/
    greedy_trajectory_baseline/
      <run_name>/
        config.json
        greedy_trajectory_raw_per_seed.csv          # new classical results, append per seed
        merged_greedy_trajectory_raw_per_seed.csv   # source VarQITE raw + classical columns, written at end
        greedy_trajectory_fair_summary_by_param.csv # comparison summary, updated after each n
        validation_mismatches.jsonl                 # if regenerated Babai/residual disagree with the source raw
        worker_errors.jsonl

Fair comparison target
----------------------
The summary directly compares:
    Greedy trajectory candidates + LWE-prior reranking
vs.
    VarQITE candidates + LWE-prior reranking

Definition of the main fair classical pool
-------------------------------------------
In this script, the classical candidate pool is intentionally restricted to:
    - zero correction, representing the greedy starting point;
    - every accepted state along the greedy trajectory;
    - the greedy final state.

No manually added single-coordinate ±1 neighbors are included.
This makes the comparison focus on:
    "candidate states naturally generated by greedy local descent"
vs.
    "candidate states sampled by VarQITE".

Both use the SAME:
    - candidate_topk from the source run's config
    - LWE-prior score weights from the source run's config
    - LWE-prior selection mode from the source run's config

The only difference is the candidate-pool generator.
"""

