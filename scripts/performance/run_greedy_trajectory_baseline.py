# =========================================================
# 8) Main
# =========================================================
def main() -> None:
    args = parse_args()
    local_cfg = build_local_cfg_from_args(args)

    source_run_dir = resolve_input_path(local_cfg["source_run_dir"])
    if source_run_dir is None:
        raise ValueError("Please set --source_run_dir to an existing main-experiment run directory.")

    source_raw_csv = source_run_dir / "raw_per_seed.csv"
    source_config_json = source_run_dir / "config.json"
    if not source_raw_csv.exists():
        raise FileNotFoundError(f"raw_per_seed.csv not found: {source_raw_csv}")
    if not source_config_json.exists():
        raise FileNotFoundError(f"config.json not found: {source_config_json}")

    with source_config_json.open("r", encoding="utf-8") as f:
        source_cfg = json.load(f)

    source_df = pd.read_csv(source_raw_csv)
    required_cols = {
        "n",
        "m",
        "q",
        "seed",
        "w_babai",
        "residual",
        "delta_exact",
        "exact_best_energy",
        "babai_secret_success",
        "exact_secret_success",
        "classical_secret_success",
        "qite_primary_secret_success",
        "qite_candidate_best_secret_success",
        "qite_candidate_any_secret_success",
        "babai_fail_but_qite_candidate_best_fix",
        "babai_fail_but_qite_candidate_any_fix",
    }
    missing = sorted(required_cols - set(source_df.columns))
    if missing:
        raise ValueError(f"Source raw_per_seed.csv is missing required columns: {missing}")

    source_records = source_df.to_dict(orient="records")

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_name = make_run_name(local_cfg, source_run_dir, source_cfg, timestamp)

    results_root = PROJECT_ROOT / "output" / "greedy_trajectory_baseline"
    run_dir = results_root / run_name
    run_dir.mkdir(parents=True, exist_ok=True)

    output_config = {
        "local_config": local_cfg,
        "source_run_dir": str(source_run_dir),
        # These two keys are part of the archived config.json schema.
        "source_exp11_config": source_cfg,
        "candidate_rerank_config_reused_from_exp11": make_candidate_rerank_config(source_cfg).to_dict(),
        "classical_candidate_generation_config": make_classical_generation_config(local_cfg, source_cfg).to_dict(),
    }
    config_json_path = run_dir / "config.json"
    with config_json_path.open("w", encoding="utf-8") as f:
        json.dump(to_jsonable(output_config), f, ensure_ascii=False, indent=2)

    classical_raw_csv_path = run_dir / "greedy_trajectory_raw_per_seed.csv"
    summary_csv_path = run_dir / "greedy_trajectory_fair_summary_by_param.csv"
    merged_raw_csv_path = run_dir / "merged_greedy_trajectory_raw_per_seed.csv"
    mismatches_jsonl_path = run_dir / "validation_mismatches.jsonl"
    errors_jsonl_path = run_dir / "worker_errors.jsonl"

    max_workers = resolve_max_workers(local_cfg)
    chunksize = max(1, int(local_cfg["parallel_chunksize"]))
    mp_start_method = str(local_cfg["mp_start_method"])

    print("\n============================================================")
    print("Greedy-trajectory-only fair baseline starts. No VarQITE rerun.")
    print(f"Source main run      : {source_run_dir}")
    print(f"Source raw rows      : {len(source_records)}")
    print(f"Output run dir       : {run_dir}")
    print(f"candidate_topk       : {source_cfg['candidate_topk']}")
    print(f"selection_mode       : {source_cfg['candidate_selection']}")
    print(f"max_workers          : {max_workers}")
    print(f"parallel_chunksize   : {chunksize}")
    print(f"mp_start_method      : {mp_start_method}")
    print("============================================================\n")

    rows: list[ClassicalOnlyRow] = []
    raw_fieldnames = list(ClassicalOnlyRow.__dataclass_fields__.keys())

    # Group source records by n so summary can be updated after each n.
    source_records_by_n: dict[int, list[dict[str, Any]]] = {}
    for rec in source_records:
        source_records_by_n.setdefault(int(rec["n"]), []).append(rec)

    for n in sorted(source_records_by_n):
        block_records = source_records_by_n[n]
        print(f"\n=== computing classical candidate baseline for n={n}, records={len(block_records)} ===")

        completed = 0
        errors = 0
        block_t0 = time.perf_counter()

        ctx = mp.get_context(mp_start_method)
        task_args = [(rec, source_cfg, local_cfg) for rec in block_records]
        with ProcessPoolExecutor(max_workers=max_workers, mp_context=ctx) as executor:
            futures = [executor.submit(worker, args) for args in task_args]
            for fut in as_completed(futures):
                seed, row, validation_issue, error = fut.result()
                completed += 1

                if error is not None:
                    errors += 1
                    append_jsonl(errors_jsonl_path, {"n": int(n), "seed": int(seed), "error": error})
                elif row is not None:
                    rows.append(row)
                    append_csv_row(classical_raw_csv_path, asdict(row), raw_fieldnames)
                    if validation_issue is not None:
                        append_jsonl(mismatches_jsonl_path, validation_issue)

                if completed % 5 == 0 or completed == len(block_records):
                    print(
                        f"[progress n={n}] completed={completed}/{len(block_records)}, "
                        f"rows={len(rows)}, errors={errors}, last_seed={seed}"
                    )

        rows.sort(key=lambda r: (int(r.n), int(r.m), int(r.q), int(r.seed)))
        summary_rows = summarize_rows(rows)
        write_csv(summary_csv_path, summary_rows)

        block_elapsed = time.perf_counter() - block_t0
        print(f"[done n={n}] errors={errors}, elapsed={block_elapsed:.2f} sec")
        print(f"[updated] classical raw : {classical_raw_csv_path}")
        print(f"[updated] fair summary  : {summary_csv_path}")

    # Final merged raw data with the source VarQITE results.
    merged = build_merged_raw(source_df, rows)
    merged.to_csv(merged_raw_csv_path, index=False, encoding="utf-8-sig")

    print("\n============================================================")
    print("Done. No VarQITE was rerun.")
    print(f"Output run dir      : {run_dir}")
    print(f"Config              : {config_json_path}")
    print(f"Greedy-trajectory raw CSV   : {classical_raw_csv_path}")
    print(f"Greedy-trajectory fair summary CSV    : {summary_csv_path}")
    print(f"Merged greedy-trajectory raw CSV      : {merged_raw_csv_path}")
    print(f"Mismatch JSONL      : {mismatches_jsonl_path}")
    print(f"Errors JSONL        : {errors_jsonl_path}")
    print("============================================================\n")

    for row in summarize_rows(rows):
        print(row)


if __name__ == "__main__":
    main()
